const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const compactDate = (d: Date) => `${String(d.getDate()).padStart(2, '0')}${MONTHS[d.getMonth()]}${d.getFullYear()}`;

/**
 * Document Naming (Figma 14158:35823):
 * "Executive Brief_Meeting Date_Account Name_v1_07Jul2026.pptx"
 */
export function briefFileName(meetingDate: string, version: string, today = new Date()) {
  const parsed = new Date(meetingDate.replace(',', ''));
  const md = Number.isNaN(parsed.getTime()) ? 'Meeting Date' : compactDate(parsed);
  const v = `v${version.split('.')[0]}`;
  return `Executive Brief_${md}_${account.name}_${v}_${compactDate(today)}.pptx`;
}
